#!/usr/bin/env node
/**
 * pr-summary.mjs — build the sticky PR comment body from a changed-file list.
 *
 * Reads newline-separated changed paths from $CHANGED_FILES (set by the PR
 * workflow via `git diff --name-only`), maps `preview/*.html` to their exact
 * `@dsCard` names, flags foundational (css/ + tokens/) changes, and prints a
 * markdown body to stdout. No emoji — the brand rule applies to tooling too.
 */
import { readPreviews, readExamples } from './build-catalog.mjs';

const changed = (process.env.CHANGED_FILES || '')
  .split('\n').map(s => s.trim()).filter(Boolean);
const RUN_URL = process.env.RUN_URL || '';
const ARTIFACT_URL = process.env.ARTIFACT_URL || '';

const previews = readPreviews();

const changedCards = changed
  .filter(f => f.startsWith('preview/') && f.endsWith('.html'))
  .map(f => previews.find(p => `preview/${p.file}` === f))
  .filter(Boolean);

const changedExamples = changed
  .filter(f => f.startsWith('examples/') && f.endsWith('.html'));

const foundational = changed.filter(f => f.startsWith('css/') || f.startsWith('tokens/'));

const out = [];
out.push('## Catalog preview');
out.push('');
out.push(`The catalog was rebuilt and all ${previews.length} specimens were screenshotted for this PR.`);
out.push('');
if (ARTIFACT_URL) out.push(`**Screenshots:** [\`catalog-screenshots\` artifact](${ARTIFACT_URL})`);
else if (RUN_URL) out.push(`**Screenshots:** download the \`catalog-screenshots\` artifact from [this run](${RUN_URL}).`);
out.push('');

if (foundational.length) {
  out.push(`**Foundational change** (\`css/\` or \`tokens/\`) — every specimen was re-rendered; review the whole catalog, not just one card.`);
  out.push('');
}
if (changedCards.length) {
  out.push('**Preview cards touched:**');
  for (const c of changedCards) out.push(`- ${c.group} — ${c.name}`);
  out.push('');
}
if (changedExamples.length) {
  out.push('**Example screens touched:**');
  for (const f of changedExamples) out.push(`- ${f.replace('examples/', '')}`);
  out.push('');
}
if (!foundational.length && !changedCards.length && !changedExamples.length) {
  out.push('No `css/`, `tokens/`, `preview/`, or `examples/` files changed — screenshots reflect the current catalog for reference.');
  out.push('');
}

out.push('---');
out.push('_Published catalog: https://epfl-enac.github.io/epfl-design-skill/ · generated by `scripts/build-catalog.mjs`_');

process.stdout.write(out.join('\n') + '\n');
